// Saves an art iteration into art/history/<asset>/vNN/ (preview PNG + frozen source + note).
// usage: node tools/snapshot.mjs <asset> <module> <exportFn> "<note>" [scale] [cols]
import { sheet, save } from './lib/raster.mjs';
import { pathToFileURL } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';

const [asset, mod, fn, note = '', scale = '6', cols = '0'] = process.argv.slice(2);
if (!asset || !mod || !fn) { console.error('usage: snapshot <asset> <module> <exportFn> "<note>" [scale] [cols]'); process.exit(1); }
const base = path.resolve('art/history', asset);
fs.mkdirSync(base, { recursive: true });
const existing = fs.readdirSync(base).filter((d) => /^v\d+$/.test(d)).map((d) => Number(d.slice(1)));
const ver = `v${String((existing.length ? Math.max(...existing) : 0) + 1).padStart(2, '0')}`;
const dir = path.join(base, ver);
fs.mkdirSync(dir, { recursive: true });

const m = await import(pathToFileURL(path.resolve(mod)).href);
const res = m[fn]();
const frames = res.frames ?? res;
const c = Number(cols) || res.cols || frames.length;
save(sheet(frames, c), path.join(dir, 'preview.png'), Number(scale), '#5a8fb0');
save(sheet(frames, c), path.join(dir, 'sheet_1x.png'), 1);
fs.copyFileSync(path.resolve(mod), path.join(dir, path.basename(mod)));
fs.writeFileSync(path.join(dir, 'NOTE.md'), `# ${asset} ${ver}\n\n${new Date().toISOString().slice(0, 10)}\n\n${note}\n`);
console.log(`snapshot ${asset}/${ver} -> ${dir}`);

// Regenerate the visual index of every asset/version (newest first per asset).
const root = path.resolve('art/history');
let md = '# Art history\n\nEvery iteration of every asset, newest first. Generated by `tools/snapshot.mjs`. Do not edit by hand.\n';
for (const a of fs.readdirSync(root).filter((d) => fs.statSync(path.join(root, d)).isDirectory()).sort()) {
  md += `\n## ${a}\n`;
  const vers = fs.readdirSync(path.join(root, a)).filter((d) => /^v\d+$/.test(d)).sort().reverse();
  for (const vv of vers) {
    const noteFile = path.join(root, a, vv, 'NOTE.md');
    const note = fs.existsSync(noteFile) ? fs.readFileSync(noteFile, 'utf8').split('\n').slice(2).join('\n').trim() : '';
    md += `\n### ${a} ${vv}\n\n${note}\n\n![${a} ${vv}](${a}/${vv}/preview.png)\n`;
  }
}
fs.writeFileSync(path.join(root, 'INDEX.md'), md);
